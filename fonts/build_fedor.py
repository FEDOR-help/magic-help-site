PEN = []


def reset():
    PEN.clear()


def poly(pts):
    PEN.append(list(pts))


def R(x0, y0, x1, y1):
    """Прямоугольник."""
    poly([(x0, y0), (x1, y0), (x1, y1), (x0, y1)])


def Q(x0, y0, x1, y1, w0, w1=DIAG):
    """Параллелограмм-штрих от (x0,y0) к (x1,y1), ширина w0 в начале, w1 в конце (перпендикулярно)."""
    dx, dy = x1 - x0, y1 - y0
    L = math.hypot(dx, dy) or 1.0
    nx, ny = -dy / L, dx / L
    a = (x0 + nx * w0 / 2, y0 + ny * w0 / 2)
    b = (x0 - nx * w0 / 2, y0 - ny * w0 / 2)
    c = (x1 - nx * w1 / 2, y1 - ny * w1 / 2)
    d = (x1 + nx * w1 / 2, y1 + ny * w1 / 2)
    poly([a, b, c, d])


def T(x, y, ang, size, w):
    """Треугольник-наконечник: вершина на (x,y) вылетает в сторону ang на size, основание w перпендикулярно."""
    a = math.radians(ang)
    ax, ay = math.cos(a), math.sin(a)
    px, py = -ay, ax
    apex = (x + ax * size, y + ay * size)
    e1 = (x + px * w / 2, y + py * w / 2)
    e2 = (x - px * w / 2, y - py * w / 2)
    poly([apex, e2, e1])


